#!/usr/bin/env node
// Generates the idempotent Construction Library seed SQL from the canonical
// source (packages/schemas/src/construction-library.seed.ts).
// Spec: docs/specs/vision/sense-vision-field-library.spec.md §7.
//
// Usage (after `pnpm --filter @semse/schemas build`):
//   node packages/db/scripts/generate-construction-library-sql.mjs > /tmp/seed.sql
//
// The output is pasted into a versioned migration. Rows use deterministic ids
// (`cli_<slug>`) and `ON CONFLICT ("slug") DO NOTHING`, so re-running it on a
// database that already has the rows is a no-op. New library items go in a
// NEW migration generated the same way — never edit an applied migration.
import { dirname, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const schemasDist = pathToFileURL(resolve(here, "../../schemas/dist/index.js")).href;
const { CONSTRUCTION_LIBRARY_SEED, normalizeLibraryText } = await import(schemasDist);

export function libraryItemId(slug) {
  return `cli_${slug.replace(/-/g, "_")}`;
}

export function buildSearchText(item) {
  const parts = [item.nameEn, item.nameEs, ...item.aliasesEn, ...item.aliasesEs, ...item.searchTerms, item.slug];
  return [...new Set(parts.map(normalizeLibraryText).filter(Boolean))].join(" | ");
}

function sqlString(value) {
  return `'${String(value).replace(/'/g, "''")}'`;
}

function sqlArray(values) {
  return values.length === 0 ? "ARRAY[]::TEXT[]" : `ARRAY[${values.map(sqlString).join(", ")}]::TEXT[]`;
}

export function buildSeedSql(items) {
  const columns = [
    "id", "slug", "canonicalName", "nameEn", "nameEs", "aliasesEn", "aliasesEs", "category", "subcategory",
    "trades", "descriptionEn", "descriptionEs", "usageEn", "usageEs", "exampleSentenceEn", "exampleSentenceEs",
    "searchTerms", "searchText", "updatedAt",
  ];
  const rows = items.map((item) => {
    const values = [
      sqlString(libraryItemId(item.slug)),
      sqlString(item.slug),
      sqlString(item.nameEn),
      sqlString(item.nameEn),
      sqlString(item.nameEs),
      sqlArray(item.aliasesEn),
      sqlArray(item.aliasesEs),
      sqlString(item.category),
      sqlString(item.subcategory),
      sqlArray(item.trades),
      sqlString(item.descriptionEn),
      sqlString(item.descriptionEs),
      sqlString(item.usageEn),
      sqlString(item.usageEs),
      sqlString(item.exampleSentenceEn),
      sqlString(item.exampleSentenceEs),
      sqlArray(item.searchTerms),
      sqlString(buildSearchText(item)),
      "CURRENT_TIMESTAMP",
    ];
    return `(${values.join(", ")})`;
  });
  return [
    `-- Construction Library seed: ${items.length} items, generated by packages/db/scripts/generate-construction-library-sql.mjs`,
    `INSERT INTO "ConstructionLibraryItem" (${columns.map((c) => `"${c}"`).join(", ")}) VALUES`,
    rows.join(",\n"),
    `ON CONFLICT ("slug") DO NOTHING;`,
    "",
  ].join("\n");
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  process.stdout.write(buildSeedSql(CONSTRUCTION_LIBRARY_SEED));
}
